const cache = new Map<Lang, Intl.DisplayNames>()

/** 两位代码 → 当前语言的名称。未知代码原样返回，不抛错。 */
export function countryName(code: string, lang: Lang): string {
    if (!code) return ''
    if (code === OTHER_COUNTRY) return code
    let names = cache.get(lang)
    if (!names) {
        names = new Intl.DisplayNames([lang === 'zh' ? 'zh-CN' : 'en'], { type: 'region' })
        cache.set(lang, names)
    }
    try {
        return names.of(code) ?? code
    } catch {
        return code
    }
}
